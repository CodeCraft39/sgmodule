"""Generate typed codecs, wire paths and .proto views from schema/youtube.json.

No downloaded compiler or library is needed for generation. The deliberately
small schema vocabulary rejects features we have not implemented rather than
silently emitting an approximate codec. Runtime operations use protobuf-ts.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'Script/Youtube/schema/youtube.json'
SCALARS = {
    'double': (1, 'number', 1), 'float': (2, 'number', 5),
    'int64': (3, 'string', 0), 'uint64': (4, 'string', 0),
    'int32': (5, 'number', 0), 'fixed64': (6, 'string', 1),
    'fixed32': (7, 'number', 5), 'bool': (8, 'boolean', 0),
    'string': (9, 'string', 2), 'bytes': (12, 'Uint8Array', 2),
    'uint32': (13, 'number', 0), 'sfixed32': (15, 'number', 5),
    'sfixed64': (16, 'string', 1), 'sint32': (17, 'number', 0),
    'sint64': (18, 'string', 0),
}


def ident(name):
    return name.replace('.', '_')


def generate(source):
    assert source['format'] == 1
    enums = source['enums']
    definitions = source['messages'] + source['requestMessages']
    by_name = {m['name']: m for m in definitions}
    assert len(by_name) == len(definitions), 'duplicate message'
    for evidence in source['evidence'].values():
        if 'sha256' in evidence:
            assert hashlib.sha256((ROOT / evidence['file']).read_bytes()).hexdigest() == evidence['sha256']
    for message in definitions:
        numbers, names = set(), set()
        assert re.fullmatch(r'[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*', message['name'])
        assert message['evidence'] in source['evidence']
        for f in message['fields']:
            assert set(f) <= {'no', 'name', 'type', 'protoName', 'repeated', 'optional'}
            assert 0 < f['no'] < 2**29 and not 19000 <= f['no'] <= 19999
            assert f['no'] not in numbers and f['name'] not in names
            numbers.add(f['no']); names.add(f['name'])
            assert re.fullmatch(r'[A-Za-z_]\w*', f['name'])
            assert f['type'] in SCALARS or f['type'] in by_name or f['type'] in enums
            assert not (f.get('optional') and f.get('repeated'))
            assert f.get('repeated') in (None, True, 'packed', 'unpacked')
            if f.get('repeated') == 'packed':
                assert f['type'] in enums or f['type'] in SCALARS and SCALARS[f['type']][2] != 2

    banner = '// Generated by tools/youtube-response/generate.py from schema/youtube.json. Do not edit.\n'
    shapes = [banner]
    for name, values in enums.items():
        shapes.append('export enum ' + ident(name) + ' {')
        for key, value in values.items():
            shapes.append(f'  {key} = {value},')
        shapes.append('}')
    response_shapes = shapes
    request_shapes = [banner]
    for m in definitions:
        shapes = request_shapes if m in source['requestMessages'] else response_shapes
        shapes.append(f'export interface {ident(m["name"])} {{')
        for f in m['fields']:
            typ = SCALARS[f['type']][1] if f['type'] in SCALARS else ident(f['type'])
            optional = '?' if not f.get('repeated') and (f['type'] in by_name or f.get('optional')) else ''
            shapes.append(f'  {f["name"]}{optional}: {typ}{"[]" if f.get("repeated") else ""};')
        shapes.append('}')

    codecs = [banner,
        "import {ProxyMessageType, UnknownFields} from '../protobuf/runtime';",
        "import type {BinaryWriteOptions, IBinaryWriter, IMessageType} from '@protobuf-ts/runtime';",
        "import * as M from './messages';",
    ]
    for m in source['messages']:
        name = m['name']; ts = ident(name)
        codecs.extend([f'class {ts}$Type extends ProxyMessageType<M.{ts}> {{', '  constructor() {',
                       f'    super({json.dumps(name)}, ['])
        for f in m['fields']:
            typ = f['type']
            kind = 'message' if typ in by_name else 'enum' if typ in enums else 'scalar'
            T = (f'() => messages[{json.dumps(typ)}]' if kind == 'message' else
                 f'() => [{json.dumps(typ)}, M.{ident(typ)}]' if kind == 'enum' else str(SCALARS[typ][0]))
            repeat = 1 if f.get('repeated') in (True, 'packed') else 2 if f.get('repeated') else 0
            opt = not repeat and (kind == 'message' or f.get('optional', False))
            codecs.append('      {' + f'no:{f["no"]}, name:{json.dumps(f.get("protoName", f["name"]))}, '
                          f'localName:{json.dumps(f["name"])}, kind:{json.dumps(kind)}, T:{T}, '
                          f'repeat:{repeat}, opt:{str(opt).lower()}' + '},')
        codecs.extend(['    ]);', '  }',
            f'  override internalBinaryWrite(message: M.{ts}, writer: IBinaryWriter, options: BinaryWriteOptions): IBinaryWriter {{'])
        for f in m['fields']:
            typ, member = f['type'], 'message.' + f['name']
            repeated = f.get('repeated')
            if typ in by_name:
                statement = f'messages[{json.dumps(typ)}].internalBinaryWrite(VALUE, writer.tag({f["no"]}, 2).fork(), options).join();'
                if repeated:
                    codecs.append(f'    for (const value of {member}) {statement.replace("VALUE", "value")}')
                else:
                    codecs.append(f'    if ({member} !== undefined) {statement.replace("VALUE", member)}')
                continue
            method = 'int32' if typ in enums else typ
            wire = 0 if typ in enums else SCALARS[typ][2]
            if repeated == 'packed':
                codecs.extend([f'    if ({member}.length) {{', f'      writer.tag({f["no"]}, 2).fork();',
                               f'      for (const value of {member}) writer.{method}(value);', '      writer.join();', '    }'])
            elif repeated:
                codecs.append(f'    for (const value of {member}) writer.tag({f["no"]}, {wire}).{method}(value);')
            else:
                if f.get('optional'):
                    condition = f'{member} !== undefined'
                elif typ in enums or typ in SCALARS and SCALARS[typ][1] == 'number':
                    condition = f'{member} !== 0'
                elif typ == 'bool':
                    condition = member
                elif typ in ('bytes', 'string'):
                    condition = f'{member}.length > 0'
                else:
                    condition = f'{member} !== "0"'
                codecs.append(f'    if ({condition}) writer.tag({f["no"]}, {wire}).{method}({member});')
        codecs.extend(['    const unknown = options.writeUnknownFields;',
            '    if (unknown !== false) (unknown === true ? UnknownFields.onWrite : unknown)(this.typeName, message, writer);',
            '    return writer;', '  }', '}'])
    codecs.append('export interface MessageMap {')
    codecs.extend(f'  {json.dumps(m["name"])}: IMessageType<M.{ident(m["name"])}>;' for m in source['messages'])
    codecs.append('}\nexport const messages: MessageMap = {')
    codecs.extend(f'  {json.dumps(m["name"])}: new {ident(m["name"])}$Type(),' for m in source['messages'])
    codecs.append('};')

    paths = [banner, 'export const wirePaths = {']
    for name, route in source['wirePaths'].items():
        current = route['root']; numbers = []
        for step in route['path']:
            f = next(f for f in by_name[current]['fields'] if f['name'] == step)
            numbers.append(f['no']); current = f['type']
        paths.append(f'  {name}: {json.dumps(numbers)},')
    paths.append('} as const;')
    paths.append('export const legacyNextFields = ' + json.dumps([f['no'] for f in by_name['youtube.response.next.Next']['fields']]) + ' as const;')
    paths.append('export const endpointMessages = {')
    for route, data in source['endpoints'].items():
        assert data['message'] in by_name
        paths.append(f'  {json.dumps(route)}: {json.dumps(data["message"])},')
    paths.append('} as const;')
    request_fields = [banner, 'export const requestFields = {']
    for m in source['requestMessages']:
        request_fields.append(f'  {m["name"].split(".")[-1]}: ' + '{' + ', '.join(f'{f["name"]}: {f["no"]}' for f in m['fields']) + '},')
    request_fields.append('} as const;')

    proto = ['syntax = "proto3";', 'package reconstructed.youtube;',
             '// Generated partial schema views. See youtube.json for evidence and limitations.']
    for name, values in enums.items():
        proto.append('enum ' + ident(name) + ' {')
        proto.extend(f'  {ident(name)}_{key} = {value};' for key, value in values.items())
        proto.append('}')
    for m in source['messages']:
        proto.extend([f'// Evidence: {m["evidence"]}', f'message {ident(m["name"])} {{'])
        for f in m['fields']:
            typ = f['type'] if f['type'] in SCALARS else ident(f['type'])
            prefix = 'repeated ' if f.get('repeated') else 'optional ' if f.get('optional') else ''
            packing = ' [packed = ' + str(f['repeated'] == 'packed').lower() + ']' if f.get('repeated') in ('packed', 'unpacked') else ''
            proto.append(f'  {prefix}{typ} {f.get("protoName", f["name"])} = {f["no"]}{packing};')
        proto.append('}')
    onesie = ['syntax = "proto3";', 'package youtube.request.init;', '// Generated from youtube.json. Requests are read without re-encoding.']
    for m in source['requestMessages']:
        onesie.append(f'message {m["name"].split(".")[-1]} {{')
        for f in m['fields']:
            onesie.append(f'  {f["type"].split(".")[-1]} {f.get("protoName", f["name"])} = {f["no"]};')
        onesie.append('}')
    return {
        'Script/Youtube/src/response/messages.ts': '\n'.join(response_shapes) + '\n',
        'Script/Youtube/src/request/messages.ts': '\n'.join(request_shapes) + '\n',
        'Script/Youtube/src/response/schema.ts': '\n'.join(codecs) + '\n',
        'Script/Youtube/src/response/wire-schema.ts': '\n'.join(paths) + '\n',
        'Script/Youtube/src/request/schema.ts': '\n'.join(request_fields) + '\n',
        'Script/Youtube/schema/response.proto': '\n'.join(proto) + '\n',
        'Script/Youtube/schema/onesie-request.proto': '\n'.join(onesie) + '\n',
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true', help='Fail on stale generated output without writing')
    args = p.parse_args()
    outputs = generate(json.loads(SOURCE.read_text()))
    for name, text in outputs.items():
        file = ROOT / name
        if args.check:
            if not file.exists() or file.read_text() != text:
                raise SystemExit('Stale generated file: ' + name)
        else:
            file.write_text(text)
    print(f'{len(outputs)} generated files {"verified" if args.check else "written"}')


if __name__ == '__main__':
    main()
